    static func usage(for keyCode: Int) -> Int? {
        map[keyCode]
    }

    static func modifierUsage(for keyCode: Int) -> Int? {
        switch keyCode {
        case 0x3B: return 0xE0 // left control
        case 0x3C: return 0xE1 // right shift
        case 0x3A: return 0xE2 // left option
        case 0x37: return 0xE3 // left command
        case 0x3E: return 0xE4 // right control
        case 0x38: return 0xE1 // left shift
        case 0x3D: return 0xE6 // right option
        case 0x36: return 0xE7 // right command
        default: return nil
        }
    }

    static func isControl(_ keyCode: Int) -> Bool { keyCode == 0x3B || keyCode == 0x3E }
    static func isOption(_ keyCode: Int) -> Bool { keyCode == 0x3A || keyCode == 0x3D }
    static func isHangul(_ keyCode: Int) -> Bool { keyCode == 0x66 || keyCode == 0x68 }
}
